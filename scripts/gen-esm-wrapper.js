'use strict'

// Generates index.mjs and the per-subpath `*-entry.mjs` files — the real ESM
// entries behind each `import` condition.
//
// It default-imports the CJS build (Node's ESM interop makes the default export
// equal to `module.exports`, which is always reliable) and then re-exports every
// top-level member as a genuine named ESM export. This gives consumers working
// `import { PrivateKey } from '@smartledger/bsv'` WITHOUT depending on
// cjs-module-lexer being able to statically detect names off `module.exports = bsv`
// (it can't — the API object is assembled at runtime).
//
// The subpath entries need it for the same reason and one more: each is
// `module.exports = require('./lib/...')`, a re-export whose names Node did not
// expose (measured on Node 22.23.3 against published 9.39.0), so `./jcs` served
// `default` alone while jcs-entry.d.ts declared a top-level `stringify` and tsc
// accepted `import { stringify }`. TypeScript permits named imports from
// CommonJS, so no declaration shape can report that mismatch — the entry has to
// provide the names. Keeping the CJS `*-entry.js` as a bare re-export preserves
// `require(...)` object identity with the underlying module; the `.mjs` beside it
// carries the named exports.
//
// Regenerated on every `npm version` bump and gated by test/build/esm_wrapper.js
// and test/build/entry_named_exports.js so no wrapper can drift from its CJS
// surface.

var fs = require('fs')
var path = require('path')

var IDENT = /^[A-Za-z_$][A-Za-z0-9_$]*$/
// Names that are reserved words / not usable as ESM export bindings.
var RESERVED = new Set([
  'default', 'import', 'export', 'const', 'let', 'var', 'function', 'class',
  'return', 'new', 'typeof', 'void', 'delete', 'in', 'instanceof', 'do', 'if',
  'else', 'switch', 'case', 'for', 'while', 'break', 'continue', 'this',
  'super', 'yield', 'await', 'enum', 'null', 'true', 'false'
])

function exportableNames (mod) {
  return Object.keys(mod)
    .filter(function (k) {
      if (!IDENT.test(k) || RESERVED.has(k)) return false
      // Skip accessor (getter) properties: destructuring them would force their
      // side effects — e.g. the SmartUTXO deprecation warning — on every ESM
      // import. They stay reachable through the default export.
      var d = Object.getOwnPropertyDescriptor(mod, k)
      return d && typeof d.get !== 'function'
    })
    .sort()
}

function render (names) {
  var lines = [
    '// GENERATED by scripts/gen-esm-wrapper.js on `npm version` — do not edit.',
    '// Real ESM entry: default + named exports over the CJS build (index.js).',
    "import bsv from './index.js'",
    '',
    'export default bsv',
    '',
    'export const {',
    names.map(function (n) { return '  ' + n }).join(',\n'),
    '} = bsv',
    ''
  ]
  return lines.join('\n')
}

// Public subpaths that resolve to a `*-entry.js`, read from the exports map so the
// generator cannot drift from the map: a new subpath gets a wrapper automatically,
// and an unmapped `*-entry.js` (bundle-entry.js) is correctly left alone.
function subpathEntries () {
  var pkg = JSON.parse(fs.readFileSync(path.join(__dirname, '../package.json'), 'utf8'))
  var out = []
  Object.keys(pkg.exports || {}).forEach(function (key) {
    var val = pkg.exports[key]
    if (!val || typeof val !== 'object') return
    var target = val.require || val.default
    var m = /^\.\/([A-Za-z0-9_-]+)-entry\.js$/.exec(target || '')
    if (m) out.push(m[1])
  })
  return out.sort()
}

function renderEntry (name, names) {
  // Underscore-prefixed members are internal by convention and some are explicitly
  // excluded from the declarations (shamir's `_*Legacy` share readers, which exist
  // only to recover pre-6.x shares). Re-exporting them as named ESM bindings would
  // promote them to supported surface, so they stay reachable through the default
  // export alone, exactly as under `require`.
  names = names.filter(function (n) { return n.charAt(0) !== '_' })
  var cjs = './' + name + '-entry.js'
  var lines = [
    '// GENERATED by scripts/gen-esm-wrapper.js on `npm version` — do not edit.',
    "// Real ESM entry for the '" + name + "' subpath: default + named exports over " + cjs + '.',
    "import mod from '" + cjs + "'",
    '',
    'export default mod'
  ]
  // An empty destructuring pattern is a syntax error, so a module with no
  // exportable names gets the default export alone (gdaf, security: both classes
  // with no own enumerable statics).
  if (names.length) {
    lines.push('', 'export const {', names.map(function (n) { return '  ' + n }).join(',\n'), '} = mod')
  }
  lines.push('')
  return lines.join('\n')
}

// { name: source } for every subpath wrapper, so callers can write or compare them.
function generateEntries () {
  var out = {}
  subpathEntries().forEach(function (name) {
    var entryPath = path.join(__dirname, '../' + name + '-entry.js')
    delete require.cache[require.resolve(entryPath)]
    var mod = require(entryPath)
    out[name] = renderEntry(name, exportableNames(mod))
  })
  return out
}

function generate () {
  // Resolve fresh so `npm version` picks up the current build.
  var indexPath = path.join(__dirname, '../index.js')
  delete require.cache[require.resolve(indexPath)]
  var bsv = require(indexPath)
  var out = render(exportableNames(bsv))
  return out
}

if (require.main === module) {
  var out = generate()
  fs.writeFileSync(path.join(__dirname, '../index.mjs'), out)
  console.log('index.mjs -> ' + out.split('\n').length + ' lines, ' +
    exportableNames(require('../index.js')).length + ' named exports')
  var entries = generateEntries()
  Object.keys(entries).forEach(function (name) {
    var file = name + '-entry.mjs'
    fs.writeFileSync(path.join(__dirname, '../' + file), entries[name])
    var named = entries[name].indexOf('export const {') === -1
      ? 0
      : entries[name].split('export const {')[1].split('} = mod')[0].split(',').length
    console.log(file + ' -> ' + named + ' named exports')
  })
}

module.exports = {
  generate: generate,
  generateEntries: generateEntries,
  subpathEntries: subpathEntries,
  exportableNames: exportableNames,
  render: render,
  renderEntry: renderEntry
}
