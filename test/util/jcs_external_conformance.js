'use strict'

/* global describe, it */

// Two EXTERNAL canaries: vectors and signatures this repository did not generate.
//
// Everything else in this suite is ours, which means a change in our own understanding moves the
// test and the code together and nothing fails. These two cannot do that:
//
//   * the JCS vectors come from SmartLedgerTechnology/attest-spec, written for another project's
//     conformance suite. `@smartledger/envelope@3.0.0` ships a comment claiming this library's
//     canonicaliser "scores 11/11 against the conformance vectors" — an unverified claim about
//     OUR code in someone else's PUBLISHED artifact until it was run on 2026-10-15. It is true.
//   * the message vector was generated by the SmartLedger wallet shell with its own vendored
//     bundle at v9.16.1, a version this tree no longer builds, and contributed as a pinned
//     fixture. It is not an independent implementation — it was made with this library — so it
//     pins wire behaviour rather than confirming correctness. That is still the thing we cannot
//     write for ourselves: a consumer's bytes, from a version we have moved past.

require('chai').should()
var bsv = require('../..')
var jcs = require('../../lib/util/jcs')
var JCS_VECTORS = require('../data/jcs-conformance-vectors.json')
var MSG_VECTOR = require('../data/external-message-vector.json')

describe('external conformance vectors', function () {
  describe('JCS, from another project\'s suite', function () {
    it('canonicalises every case exactly', function () {
      JCS_VECTORS.cases.length.should.be.above(0)
      JCS_VECTORS.cases.forEach(function (c) {
        jcs.stringify(c.input).should.equal(c.expected, c.name)
      })
    })

    it('gets the integer-like-key case right, which is the one that distinguishes implementations', function () {
      // JavaScript hands back integer-like keys first in ascending NUMERIC order, so a
      // canonicaliser that sorts and then rebuilds an object silently loses the sort. JCS wants
      // UTF-16 order, in which "10" precedes "2". Reported independently by a wallet consumer on
      // the day these vectors were first run here, which is how two parties find the same trap.
      Object.keys(JSON.parse('{"2":"a","10":"b","alpha":"c"}')).should.deep.equal(['2', '10', 'alpha'])
      jcs.stringify({ 2: 'two', 10: 'ten', b: 1, a: 2 })
        .should.equal('{"10":"ten","2":"two","a":2,"b":1}')
    })
  })

  describe('a message signature from a consumer, generated on 9.16.1', function () {
    var key = bsv.HDPrivateKey.fromSeed(Buffer.from(MSG_VECTOR.derivation.seed, 'hex'))
      .deriveChild(MSG_VECTOR.derivation.path).privateKey
    var message = Buffer.from(MSG_VECTOR.messageHex, 'hex').toString('utf8')

    it('derives the same key material from the same seed and path', function () {
      key.toAddress().toString().should.equal(MSG_VECTOR.derivation.address)
      key.toPublicKey().toHex().should.equal(MSG_VECTOR.derivation.publicKey)
    })

    it('is the shape that makes it a canary: 367 bytes with embedded newlines', function () {
      // A short ASCII string exercises neither the varint length nor the UTF-8 path.
      Buffer.from(MSG_VECTOR.messageHex, 'hex').length.should.equal(367)
      ;(message.match(/\n/g) || []).length.should.equal(4)
    })

    it('computes the same magic hash', function () {
      bsv.Message(message).magicHash().toString('hex').should.equal(MSG_VECTOR.magicHash)
    })

    it('produces the identical signature, byte for byte', function () {
      // Deterministic (RFC 6979), so this is reproducible rather than merely verifiable.
      bsv.Message(message).sign(key).should.equal(MSG_VECTOR.signature)
    })

    it('verifies it at the right address and REFUSES it at the wrong one', function () {
      // The negative case is the whole reason the positive one means anything: a verifier
      // that returned true unconditionally would pass the line above.
      bsv.Message(message).verify(MSG_VECTOR.verifiesAt, MSG_VECTOR.signature).should.equal(true)
      bsv.Message(message).verify(MSG_VECTOR.doesNotVerifyAt, MSG_VECTOR.signature).should.equal(false)
    })
  })
})
